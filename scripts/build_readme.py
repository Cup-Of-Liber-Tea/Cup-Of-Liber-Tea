def main():
    # Define the order of components
    components = [
        "header.md",
        "hud.md",
        "skills.md",
        "time_greeting",
        "web_status.md", # Generated by GitHub Actions Shell Script
        "snake.md",
        "chess.md",
        "meme.md",
        "weather.md",
        "minesweeper.md",
        "graph.md",
        "stats.md",
        "community.md"
    ]
    
    current_dir = os.path.dirname(os.path.abspath(__file__))
    project_root = os.path.dirname(current_dir)
    
    readme_content = ""
    
    print(f"Building README from {project_root}...")

    for component in components:
        if component == "time_greeting":
            readme_content += get_time_greeting() + "\n"
            print("Added Time Greeting")
            continue
            
        component_path = os.path.join(project_root, "components", component)
        
        if os.path.exists(component_path):
            with open(component_path, "r", encoding="utf-8") as f:
                readme_content += f.read() + "\n"
                print(f"Added {component}")
        else:
            # web_status.md might not exist locally, which is fine
            if component != "web_status.md":
                print(f"Warning: Component {component} not found at {component_path}")
            
    output_path = os.path.join(project_root, "readme.md")
    
    with open(output_path, "w", encoding="utf-8") as f:
        f.write(readme_content)
    
    print(f"Successfully generated README.md at {output_path}")

if __name__ == "__main__":
    main()
