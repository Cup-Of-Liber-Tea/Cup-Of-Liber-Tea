import os
import datetime

def get_time_greeting():
    """
    Returns a greeting message based on current KST time.
    """
    # UTC to KST (UTC+9)
    kst_now = datetime.datetime.utcnow() + datetime.timedelta(hours=9)
    hour = kst_now.hour
    
    greeting = ""
    
    if 6 <= hour < 9:
        greeting = "🌅 Good Morning! 커피부터 마시자."
    elif 9 <= hour < 12:
        greeting = "💻 오전 코딩 집중! (버그 심는 중?)"
    elif 12 <= hour < 13:
        greeting = "🍱 점심시간. 키보드에서 손 떼."
    elif 13 <= hour < 18:
        greeting = "☕ 오후의 홍차... 가 아니라 카페인 폭탄 필요."
    elif 18 <= hour < 20:
        greeting = "🏠 칼퇴 기원 (하지만 커밋은 하고 가야지?)"
    elif 20 <= hour < 23:
        greeting = "🌙 야간 코딩. 새벽 감성으로 코드 짜지 마라."
    elif 23 <= hour < 2:
        greeting = "🔥 Midnight Coding. 지금 자면 꿈을 꾸지만, 코딩하면 꿈을 이룬다."
    else:
        greeting = "🧟‍♂️ 새벽 3시 넘었다. 제발 좀 자라..."
        
    return f"""
<div align="center">
  <h3>⏰ {kst_now.strftime('%H:%M')} (KST) - {greeting}</h3>
</div>
<br/>
"""

